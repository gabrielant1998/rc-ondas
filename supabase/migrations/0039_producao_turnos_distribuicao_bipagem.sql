create function public.prod_turno_salvar(p_id smallint, p_nome text, p_entrada time, p_saida time,
  p_dias smallint[], p_int_ini time, p_int_fim time, p_ativo boolean)
returns smallint language plpgsql security definer set search_path = '' as $$
declare v public.prod_turnos; novo smallint; em text := private.gestor_email();
begin
  if not ((select private.g_admin()) or (select private.g_pode('config'))) then
    raise exception 'Sem permissão para alterar turnos' using errcode = '42501'; end if;
  if p_int_ini is not null and p_saida is not null and p_saida > p_entrada
     and not (p_int_ini >= p_entrada and p_int_fim <= p_saida and p_int_fim > p_int_ini) then
    raise exception 'O intervalo precisa ficar dentro do horário do turno' using errcode = '23514'; end if;
  if p_id is null then
    insert into public.prod_turnos (nome, entrada, saida, dias, int_ini, int_fim, ativo)
    values (btrim(p_nome), p_entrada, p_saida, coalesce(p_dias, array[1,2,3,4,5,6]::smallint[]), p_int_ini, p_int_fim, coalesce(p_ativo, true))
    returning id into novo;
    insert into public.prod_auditoria (tabela, registro, acao, depois, email)
    select 'prod_turnos', novo::text, 'criar', to_jsonb(t), em from public.prod_turnos t where t.id = novo;
    return novo;
  end if;
  select * into v from public.prod_turnos where id = p_id for update;
  if not found then raise exception 'Turno não encontrado' using errcode = '23503'; end if;
  update public.prod_turnos set nome = btrim(p_nome), entrada = p_entrada, saida = p_saida,
    dias = coalesce(p_dias, v.dias), int_ini = p_int_ini, int_fim = p_int_fim, ativo = coalesce(p_ativo, v.ativo), atualizado_em = now()
  where id = p_id;
  insert into public.prod_auditoria (tabela, registro, acao, antes, depois, email)
  select 'prod_turnos', p_id::text, 'alterar', to_jsonb(v), to_jsonb(t), em from public.prod_turnos t where t.id = p_id;
  return p_id;
end $$;

-- Nova atribuição a partir de p_desde: encerra a anterior no mesmo instante (o histórico fica)
create function public.prod_atribuir(p_operador uuid, p_andar text, p_atividade text, p_turno smallint,
  p_entrada time, p_saida time, p_situacao text, p_desde timestamptz)
returns uuid language plpgsql security definer set search_path = '' as $$
declare op public.operadores; atual public.prod_atribuicoes; novo uuid; em text := private.gestor_email(); d timestamptz := coalesce(p_desde, now());
begin
  if not (select private.g_pode_operador(p_operador, 'config')) then
    raise exception 'Sem permissão para distribuir esta pessoa' using errcode = '42501'; end if;
  select * into op from public.operadores where id = p_operador and excluido_em is null for update;
  if not found then raise exception 'Pessoa não encontrada' using errcode = '23503'; end if;
  if not exists (select 1 from public.prod_turnos where id = p_turno) then
    raise exception 'Turno não encontrado' using errcode = '23503'; end if;
  if (p_entrada is null) <> (p_saida is null) then
    raise exception 'Informe entrada e saída do horário individual, ou deixe os dois em branco' using errcode = '23514'; end if;
  if d > now() + interval '60 days' or d < now() - interval '2 days' then
    raise exception 'A data de início precisa estar entre 2 dias atrás e 60 dias à frente' using errcode = '23514'; end if;
  select * into atual from public.prod_atribuicoes where operador_id = p_operador and fim is null;
  if found then
    if d <= atual.inicio then
      if exists (select 1 from public.prod_bipagens b where b.atribuicao_id = atual.id) then
        raise exception 'Já existem bipagens nesta distribuição. A mudança precisa começar depois de %', to_char(atual.inicio at time zone 'America/Sao_Paulo', 'DD/MM HH24:MI') using errcode = '23514'; end if;
      -- atribuição ainda sem bipagens: substitui (fica registrado na auditoria)
      insert into public.prod_auditoria (tabela, registro, acao, antes, email) values ('prod_atribuicoes', atual.id::text, 'substituir', to_jsonb(atual), em);
      delete from public.prod_atribuicoes where id = atual.id;
    else
      update public.prod_atribuicoes set fim = d where id = atual.id;
      insert into public.prod_auditoria (tabela, registro, acao, antes, email) values ('prod_atribuicoes', atual.id::text, 'encerrar', to_jsonb(atual), em);
    end if;
  end if;
  insert into public.prod_atribuicoes (operador_id, andar, atividade, turno_id, entrada, saida, situacao, inicio, criado_por)
  values (p_operador, p_andar, p_atividade, p_turno, p_entrada, p_saida, coalesce(p_situacao, 'ativo'), d, coalesce(em, 'sistema'))
  returning id into novo;
  insert into public.prod_auditoria (tabela, registro, acao, depois, email)
  select 'prod_atribuicoes', novo::text, 'criar', to_jsonb(a), coalesce(em, 'sistema') from public.prod_atribuicoes a where a.id = novo;
  return novo;
end $$;

-- Postos atuais (para o aparelho da produção mostrar onde a pessoa está). Sem dados sensíveis.
create function public.prod_postos()
returns table (operador_id uuid, andar text, atividade text, turno_id smallint, entrada time, saida time, situacao text, inicio timestamptz)
language sql stable security definer set search_path = '' as $$
  select a.operador_id, a.andar, a.atividade, a.turno_id, a.entrada, a.saida, a.situacao, a.inicio
  from public.prod_atribuicoes a join public.operadores o on o.id = a.operador_id and o.excluido_em is null
  where a.fim is null limit 2000
$$;

-- Registro de bipagens (lote, usado também pela fila sem internet). Resposta item a item.
-- resultado: ok | ja_existia | wn_repetido | sem_posto | recusada
create function public.registrar_embalagens(lote jsonb)
returns table (id uuid, resultado text, detalhe text, coletado boolean, presenca_nova boolean, andar text, atividade text)
language plpgsql security definer set search_path = '' as $$
declare o jsonb; op public.operadores; a public.prod_atribuicoes; t public.prod_turnos; quando timestamptz; loc timestamp;
        ent time; sai time; d date; n integer; wn_n text;
begin
  if jsonb_typeof(lote) <> 'array' or jsonb_array_length(lote) > 200 then
    raise exception 'Envie uma lista com até 200 bipagens' using errcode = '22023'; end if;
  for o in select * from jsonb_array_elements(lote) loop
    id := null; detalhe := null; coletado := null; presenca_nova := false; andar := null; atividade := null;
    begin
      id := (o ->> 'id')::uuid;
      quando := (o ->> 'bipada_em')::timestamptz;
      if quando is null or quando > now() + interval '5 minutes' or quando < now() - interval '2 days' then
        resultado := 'recusada'; detalhe := 'Horário da bipagem fora do intervalo aceito'; return next; continue; end if;
      if coalesce(length(btrim(o ->> 'wn')), 0) not between 1 and 40 then
        resultado := 'recusada'; detalhe := 'Número da onda inválido'; return next; continue; end if;
      select * into op from public.operadores x where x.id = (o ->> 'operador_id')::uuid and x.excluido_em is null;
      if not found then resultado := 'recusada'; detalhe := 'Pessoa não encontrada'; return next; continue; end if;
      select * into a from public.prod_atribuicoes x
       where x.operador_id = op.id and x.inicio <= quando and (x.fim is null or x.fim > quando)
       order by x.inicio desc limit 1;
      if not found or a.situacao <> 'ativo' then
        resultado := 'sem_posto'; detalhe := op.nome || ' ainda não tem posto na produção. Fale com o gestor.'; return next; continue; end if;
      select * into t from public.prod_turnos x where x.id = a.turno_id;
      andar := a.andar; atividade := a.atividade;
      -- dia operacional: em turno que passa da meia-noite, a madrugada pertence ao dia de entrada
      loc := quando at time zone 'America/Sao_Paulo';
      ent := coalesce(a.entrada, t.entrada); sai := coalesce(a.saida, t.saida);
      d := loc::date;
      if sai is not null and sai <= ent and loc::time < sai then d := d - 1; end if;
      wn_n := public.normaliza_wn(o ->> 'wn');
      coletado := exists (select 1 from public.ondas w where w.wn_norm = wn_n);
      insert into public.prod_bipagens (id, wn, operador_id, galpao_id, atribuicao_id, andar, atividade, turno_id, dia, bipada_em)
      values (id, btrim(o ->> 'wn'), op.id, op.galpao_id, a.id, a.andar, a.atividade, a.turno_id, d, quando)
      on conflict on constraint prod_bipagens_pkey do nothing;
      get diagnostics n = row_count;
      if n = 0 then
        if exists (select 1 from public.prod_bipagens b where b.id = (o ->> 'id')::uuid and b.operador_id = op.id) then
          resultado := 'ja_existia';
        else resultado := 'recusada'; detalhe := 'Identificador já usado por outra bipagem'; end if;
        return next; continue; end if;
      insert into public.prod_presenca (operador_id, dia, primeira_id, primeira_em, turno_id, andar, atividade)
      values (op.id, d, id, quando, a.turno_id, a.andar, a.atividade)
      on conflict (operador_id, dia) do nothing;
      get diagnostics n = row_count;
      presenca_nova := n = 1;
      resultado := 'ok';
    exception
      when unique_violation then
        resultado := 'wn_repetido';
        detalhe := 'A onda ' || coalesce(o ->> 'wn', '') || ' já foi embalada na ' || case atividade when 'maquina' then 'Máquina' else 'Mesa' end;
      when others then resultado := 'recusada'; detalhe := sqlerrm;
    end;
    return next;
  end loop;
end $$;

-- Bipagens de um dia para os aparelhos da produção (status de coleta calculado na hora da leitura)
create function public.prod_bipagens_dia(p_dia date)
returns table (id uuid, wn text, operador_id uuid, andar text, atividade text, turno_id smallint, bipada_em timestamptz, coletado boolean)
language sql stable security definer set search_path = '' as $$
  select b.id, b.wn, b.operador_id, b.andar, b.atividade, b.turno_id, b.bipada_em,
         exists (select 1 from public.ondas w where w.wn_norm = b.wn_norm)
  from public.prod_bipagens b
  where p_dia between current_date - 7 and current_date + 1 and b.dia = p_dia
  order by b.bipada_em desc limit 8000
$$;

