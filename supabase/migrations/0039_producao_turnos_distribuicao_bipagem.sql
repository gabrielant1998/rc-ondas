-- Produção (embalagem) no galpão RC: turnos próprios, distribuição das pessoas por andar e atividade,
-- bipagem das ondas para embalar e presença automática pela primeira bipagem do dia.
-- Não altera nenhuma tabela da Coleta. A onda da Coleta só é lida para dizer se foi coletada.
-- Para desfazer: drop das funções prod_* e das tabelas prod_*, e voltar a regra de abas de gestores.

-- 1) Turnos da produção (horários editáveis; saída em branco = ainda não configurada)
create table public.prod_turnos (
  id        smallint generated by default as identity primary key,
  nome      text not null check (length(btrim(nome)) between 1 and 40),
  entrada   time not null,
  saida     time,
  dias      smallint[] not null default array[1,2,3,4,5,6]::smallint[]
            check (cardinality(dias) between 1 and 7 and dias <@ array[0,1,2,3,4,5,6]::smallint[]),
  int_ini   time,
  int_fim   time,
  ativo     boolean not null default true,
  atualizado_em timestamptz not null default now(),
  check ((int_ini is null) = (int_fim is null))
);
insert into public.prod_turnos (id, nome, entrada) values (1, '1º turno', '06:00'), (2, '2º turno', '09:00');
select setval(pg_get_serial_sequence('public.prod_turnos', 'id'), 2);

-- 2) Distribuição: onde cada pessoa trabalha, com vigência. Uma atribuição aberta por pessoa.
create table public.prod_atribuicoes (
  id          uuid primary key default gen_random_uuid(),
  operador_id uuid not null references public.operadores(id),
  andar       text not null check (andar in ('terreo', 'mezanino')),
  atividade   text not null check (atividade in ('mesa', 'maquina')),
  turno_id    smallint not null references public.prod_turnos(id),
  entrada     time,               -- horário individual (em branco = do turno)
  saida       time,
  situacao    text not null default 'ativo' check (situacao in ('ativo', 'inativo')),
  inicio      timestamptz not null,
  fim         timestamptz check (fim is null or fim > inicio),
  criado_por  text not null,
  criado_em   timestamptz not null default now()
);
create unique index prod_atribuicoes_aberta_uq on public.prod_atribuicoes (operador_id) where fim is null;
create index prod_atribuicoes_operador_idx on public.prod_atribuicoes (operador_id, inicio desc);
create index prod_atribuicoes_turno_idx on public.prod_atribuicoes (turno_id);

-- 3) Bipagens da produção. Cada uma guarda andar, atividade e turno do momento (o histórico não muda depois).
create table public.prod_bipagens (
  id            uuid primary key,                 -- gerado no aparelho: reenviar não duplica
  wn            text not null check (length(btrim(wn)) between 1 and 40),
  wn_norm       text generated always as (public.normaliza_wn(wn)) stored,
  operador_id   uuid not null references public.operadores(id),
  galpao_id     uuid references public.galpoes(id),
  atribuicao_id uuid not null references public.prod_atribuicoes(id),
  andar         text not null,
  atividade     text not null,
  turno_id      smallint not null references public.prod_turnos(id),
  dia           date not null,                    -- dia operacional (turno que passa da meia-noite fica no dia de entrada)
  bipada_em     timestamptz not null,
  origem        text not null default 'bipagem',
  criada_em     timestamptz not null default now()
);
create unique index prod_bipagens_wn_atividade_uq on public.prod_bipagens (wn_norm, atividade);  -- uma vez na Mesa e uma na Máquina
create index prod_bipagens_dia_idx on public.prod_bipagens (dia, bipada_em);
create index prod_bipagens_operador_idx on public.prod_bipagens (operador_id, dia);
create index prod_bipagens_atribuicao_idx on public.prod_bipagens (atribuicao_id);
create index prod_bipagens_turno_idx on public.prod_bipagens (turno_id);
create index prod_bipagens_galpao_idx on public.prod_bipagens (galpao_id);

-- 4) Presença operacional: uma por pessoa e dia, gravada pela primeira bipagem válida
create table public.prod_presenca (
  operador_id     uuid not null references public.operadores(id),
  dia             date not null,
  primeira_id     uuid not null references public.prod_bipagens(id),
  primeira_em     timestamptz not null,
  turno_id        smallint not null references public.prod_turnos(id),
  andar           text not null,
  atividade       text not null,
  origem          text not null default 'bipagem',
  primary key (operador_id, dia)
);
create index prod_presenca_primeira_idx on public.prod_presenca (primeira_id);
create index prod_presenca_turno_idx on public.prod_presenca (turno_id);

-- 5) Auditoria de turnos e distribuição
create table public.prod_auditoria (
  id          bigint generated always as identity primary key,
  tabela      text not null,
  registro    text not null,
  acao        text not null,
  antes       jsonb,
  depois      jsonb,
  email       text not null,
  em          timestamptz not null default now()
);
create index prod_auditoria_em_idx on public.prod_auditoria (em desc);

